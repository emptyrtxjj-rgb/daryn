function finalize(quiz) {
  return {
    ...JSON.parse(JSON.stringify(quiz)),
    question_count: quiz.questions.length,
    total_points: quiz.questions.reduce((sum, q) => sum + q.points, 0),
    skipped_questions: 0,
    demo: true,
  };
}

function getDemoQuiz(language) {
  return finalize(language === 'kz' ? KZ : RU);
}

